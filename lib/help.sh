#!/bin/bash
# Help display functions for vb_tool

[[ -n "$_VB_HELP_LOADED" ]] && return 0
_VB_HELP_LOADED=1

show_help() {
    echo "Vastbase Script Tool (vb_tool)"
    echo ""
    echo "Usage Summary:"
    echo "  vb_tool <command> [options]"
    echo "  Example: vb_tool as <vb_pid>"
