flamegraph_help() {
    echo "Options for flamegraph:"
    echo "  Usage: vb_tool flamegraph [-p <pid>] [-s <seconds>]"
    echo "  Description: collect CPU perf data and generate an interactive SVG flame graph"
    echo "  Options:"
    echo "    -p: target process PID (optional, default: sample all processes)"
    echo "    -s: sampling duration in seconds (optional, default: 10)"
    echo "  Output: flame graph SVG saved to /tmp/perf_<date>.svg"
    echo ""
}
run_flamegraph() {
    local PID=""
    local SLEEP=10
    local OUTPUT_DIR=/tmp
    local SVG_FILE="$OUTPUT_DIR/perf_$(date +'%Y%m%d_%H%M%S').svg"
    local FLAMEGRAPH_DIR
    FLAMEGRAPH_DIR=$(mktemp -d /tmp/flamegraph_tools_XXXXXX)

    # ---------- cleanup on exit ----------
    trap "rm -rf '$FLAMEGRAPH_DIR'" RETURN

    # ---------- parse options ----------
    local OPTIND=1
    while getopts "p:s:" opt; do
        case $opt in
            p) PID=$OPTARG ;;
            s) SLEEP=$OPTARG ;;
            *)
                echo "Error: unknown option -$OPTARG" >&2
                return 1
                ;;
        esac
    done

    if ! [[ "$SLEEP" =~ ^[0-9]+$ ]] || [ "$SLEEP" -lt 1 ]; then
        echo "Error: -s must be a positive integer" >&2
        return 1
    fi

    if [ -n "$PID" ] && ! [[ "$PID" =~ ^[0-9]+$ ]]; then
        echo "Error: -p must be a numeric PID" >&2
        return 1
    fi

    # ---------- check dependencies ----------
    if ! command -v perf >/dev/null 2>&1; then
        echo "Error: 'perf' not found. Please install linux-tools or perf package." >&2
        return 1
    fi
    if ! command -v perl >/dev/null 2>&1; then
        echo "Error: 'perl' not found." >&2
        return 1
    fi

    # ---------- write embedded stackcollapse-perf.pl ----------
